    if (lower.contains('alibaug')) {
      return [alibaug1, alibaug2, alibaug3][index % 3];
    }
    if (lower.contains('lonavala')) {
      return [lonavala1, lonavala2, lonavala3][index % 3];
    }
    if (lower.contains('rajmachi')) {
      return [rajmachi1, rajmachi2][index % 2];
    }
    if (lower.contains('kasol')) {
      return [kasol1, kasol2, kasol3][index % 3];
    }
    if (lower.contains('manali')) {
      return [manali1, manali2, manali3][index % 3];
    }
    if (lower.contains('rishikesh')) {
      return [rishikesh1, rishikesh2][index % 2];
    }
    if (lower.contains('gokarna')) {
      return [gokarna1, gokarna2][index % 2];
    }
    if (lower.contains('munnar')) {
      return [munnar1, munnar2][index % 2];
    }
    if (lower.contains('coorg')) {
      return [coorg1, coorg2][index % 2];
    }
    if (lower.contains('kashmir')) {
      return [kashmir1, kashmir2][index % 2];
    }
    if (lower.contains('jaipur')) {
      return [jaipur1, jaipur2][index % 2];
